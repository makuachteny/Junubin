async function seed() {
  console.log('Seeding database...');
  const passwordHash = await bcrypt.hash('seed12345', 12);

  for (const p of SEED_PROFILES) {
    const existing = await prisma.user.findUnique({ where: { email: p.email } });
    if (existing) {
      console.log(`  Skipping ${p.displayName} (already exists)`);
      continue;
    }

    const user = await prisma.user.create({
      data: {
        email: p.email,
        passwordHash,
        displayName: p.displayName,
        dateOfBirth: new Date(p.dateOfBirth),
        gender: p.gender,
        countryCode: p.countryCode,
        city: p.city,
        isVerified: true,
        profile: {
          create: {
            bio: p.bio,
            lookingFor: p.lookingFor,
            datingIntentions: p.datingIntentions,
            ethnicity: p.ethnicity,
            heightCm: p.heightCm,
            pronouns: p.pronouns,
            education: p.education,
            children: p.children,
            job: p.job,
            school: p.school || null,
            interests: p.interests,
            stickers: p.stickers,
            profileComplete: true,
          },
        },
        photos: {
          create: p.photos.map((filename, i) => ({
            url: `https://res.cloudinary.com/placeholder/image/upload/junubin/seed/${filename}`,
            sortOrder: i,
            isPrimary: i === 0,
          })),
        },
      },
    });
    console.log(`  Created: ${p.displayName} (${user.id})`);
  }

  console.log('Seeding complete!');
}

seed()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
